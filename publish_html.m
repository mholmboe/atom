%% publish_html
% This MATLAB .m file generates the html documentation in the html/ folder,
% which is also what the online documentation site is built from.
%
% Run it from the top level of the atom Toolbox (the folder holding this
% file), with the toolbox on the MATLAB path:
%
%   cd /path/to/atom
%   publish_html
%
% Every function header is rendered with evalCode=false, so no example code
% is executed and no figures are produced. The last step builds the
% searchable index used by MATLAB's own doc browser.
%
%% Version
% 3.0.2
%
%% Contact
% Please report problems/bugs to michael.holmboe@umu.se
%

%% Set the path's
atompath=pwd;
docpath=strcat(atompath,'/html');

%% The lists
filelist = {...
    %'Available_functions.m',...
    'index.m',...
    'GettingStarted.m',...
    'Common_variables.m',...
    'Examples.m',...
    'Structures_and_solvents.m',...
    'List_all_functions.m',...
    'List_all_functions_topics.m',...
    'List_build_functions.m',...
    'List_custom_functions.m',...
    'List_export_functions.m',...
    'List_ff_opt_functions.m',...
    'List_forcefield_functions.m',...
    'List_general_functions.m',...
    'List_import_functions.m',...
    'List_neigh_functions.m',...
    'List_structures.m',...
    'List_variables.m',...
    };

for i=1:length(filelist)
    filelist{i}
    publish(filelist{i},'createThumbnail',true,'maxWidth',1200,'evalCode',false,'outputDir',docpath)
end

%% The functions, in each subfolder
dirs={...
    'build_functions';...
    'custom_functions';...
    'examples/Basic_examples';...
    'examples/Build_a_2xlayer_clay_system';...
    'export_functions';...
    'external';...
    'ff_opt';...
    'forcefield_functions';...
    'general_functions';...
    'import_functions';...
    'neigh_functions';...
    'structures';...
    'variables';...
    };

new_list={};
for j=1:size(dirs,1)
    
    cd(char(dirs(j)))
    filelist = dir('*.m')
    
    dirs(j)
    
    for i=1:size(filelist,1)
        
        if ~isfile(filelist(i).name)
            new_list={new_list;[dirs(j) filelist(i).name]};
            dirs(j)
            filelist(i).name
            pause
        end
        filelist(i).name
        publish(filelist(i).name,'createThumbnail',true,'maxWidth',1200,'evalCode',false,'outputDir',docpath)
    end
    
    cd(atompath)
    
end

%% Lastly, build a searchable html-index
builddocsearchdb(docpath)

new_list
